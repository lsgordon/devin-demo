/** Writes mock-oidc/login.html (click-to-log-in persona page for the mock IdP) from src/platform/auth/personas.ts. */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { PERSONAS, MOCK_TENANT_ID } from "../src/platform/auth/personas";

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

const buttons = PERSONAS.map((p) => {
  const claims = {
    oid: p.oid,
    tid: MOCK_TENANT_ID,
    preferred_username: p.preferred_username,
    name: p.name,
    roles: p.roles,
    ver: "2.0",
  };
  return `    <form method="post">
      <input type="hidden" name="username" value="${p.oid}">
      <input type="hidden" name="claims" value="${esc(JSON.stringify(claims))}">
      <button type="submit" data-persona="${p.key}">
        <strong>${esc(p.name)}</strong><br><span>${esc(p.preferred_username)}</span><br><em>${esc(p.roles.join(", ") || "no roles")}</em>
      </button>
    </form>`;
}).join("\n");

const html = `<!DOCTYPE html>
<!-- AUTO-GENERATED by scripts/generate-mock-login.ts from src/platform/auth/personas.ts. MOCK IdP ONLY. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>Mock Entra ID sign-in (local only)</title>
  <style>
    body { font-family: system-ui, sans-serif; background: #f4f5f7; margin: 0; padding: 2rem; }
    h1 { font-size: 1.3rem; } p { color: #555; }
    .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(230px, 1fr)); gap: .75rem; max-width: 1000px; }
    button { width: 100%; text-align: left; padding: .75rem; border: 1px solid #ccd; border-radius: 8px; background: #fff; cursor: pointer; font-size: .9rem; }
    button:hover { border-color: #0b5cff; } em { color: #0b5cff; font-style: normal; font-size: .8rem; } span { color: #666; font-size: .8rem; }
  </style>
</head>
<body>
  <h1>Mock IdP: pick a persona</h1>
  <p>Local development only. Issues Entra-shaped tokens (oid, tid, preferred_username, roles) for tenant ${MOCK_TENANT_ID}.</p>
  <div class="grid">
${buttons}
  </div>
</body>
</html>
`;

writeFileSync(path.resolve(import.meta.dirname, "..", "mock-oidc", "login.html"), html);
console.log(`mock-oidc/login.html: ${PERSONAS.length} personas`);
