/** Writes mock-oidc/login.html (click-to-log-in persona page for the mock IdP) from src/platform/auth/personas.ts. */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { PERSONAS, MOCK_TENANT_ID } from "../src/platform/auth/personas";

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

const GROUPS: { title: string; match: (roles: readonly string[]) => boolean }[] = [
  { title: "KYC", match: (r) => r.some((x) => x.startsWith("kyc_")) },
  { title: "Refunds", match: (r) => r.some((x) => x.startsWith("refunds_")) },
  { title: "Feature flags", match: (r) => r.some((x) => x.startsWith("flags_")) },
  { title: "Audit and access", match: () => true },
];

const initials = (name: string) => name.split(/\s+/).map((w) => w[0]).slice(0, 2).join("").toUpperCase();

const card = (p: (typeof PERSONAS)[number]) => {
  const claims = {
    oid: p.oid,
    tid: MOCK_TENANT_ID,
    preferred_username: p.preferred_username,
    name: p.name,
    roles: p.roles,
    ver: "2.0",
  };
  const roles = p.roles.length ? p.roles.map((r) => `<span class="role">${esc(r)}</span>`).join("") : `<span class="role none">no roles</span>`;
  return `      <form method="post">
        <input type="hidden" name="username" value="${p.oid}">
        <input type="hidden" name="claims" value="${esc(JSON.stringify(claims))}">
        <button type="submit" data-persona="${p.key}">
          <span class="avatar">${esc(initials(p.name))}</span>
          <span class="who"><strong>${esc(p.name)}</strong><span class="email">${esc(p.preferred_username)}</span>${roles}</span>
        </button>
      </form>`;
};

const remaining = [...PERSONAS];
const sections = GROUPS.map((g) => {
  const members = remaining.filter((p) => g.match(p.roles));
  for (const m of members) remaining.splice(remaining.indexOf(m), 1);
  return members.length
    ? `  <section>\n    <h2>${esc(g.title)}</h2>\n    <div class="grid">\n${members.map(card).join("\n")}\n    </div>\n  </section>`
    : "";
}).filter(Boolean).join("\n");

const html = `<!DOCTYPE html>
<!-- AUTO-GENERATED by scripts/generate-mock-login.ts from src/platform/auth/personas.ts. MOCK IdP ONLY. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Sign in · Test identity provider</title>
  <style>
    * { box-sizing: border-box; }
    body { font-family: ui-sans-serif, system-ui, -apple-system, "Segoe UI", Roboto, sans-serif; font-size: 14px; color: #111827; background: #f8fafc; margin: 0; padding: 3rem 1.5rem; -webkit-font-smoothing: antialiased; }
    .wrap { max-width: 1040px; margin: 0 auto; }
    header { display: flex; align-items: center; gap: .9rem; margin-bottom: 2rem; }
    .logo { display: grid; place-items: center; width: 44px; height: 44px; border-radius: 11px; background: linear-gradient(135deg, #2563eb, #7c3aed); color: #fff; font-weight: 700; }
    h1 { font-size: 1.5rem; margin: 0; letter-spacing: -.01em; }
    header p { margin: .2rem 0 0; color: #6b7280; }
    .tag { display: inline-block; margin-left: .5rem; padding: .1rem .5rem; border-radius: 999px; background: #fffaeb; color: #b54708; font-size: .72rem; font-weight: 600; vertical-align: middle; }
    section { margin-bottom: 1.75rem; }
    h2 { font-size: .75rem; text-transform: uppercase; letter-spacing: .06em; color: #6b7280; margin: 0 0 .6rem; }
    .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(290px, 1fr)); gap: .75rem; }
    form { margin: 0; }
    button { display: flex; align-items: flex-start; gap: .75rem; width: 100%; height: 100%; text-align: left; padding: .9rem 1rem; border: 1px solid #e5e7eb; border-radius: 10px; background: #fff; cursor: pointer; font: inherit; color: inherit; box-shadow: 0 1px 2px rgba(16,24,40,.05); transition: border-color .15s, box-shadow .15s; }
    button:hover { border-color: #93c5fd; box-shadow: 0 4px 12px rgba(37,99,235,.1); }
    .avatar { flex: none; display: grid; place-items: center; width: 36px; height: 36px; border-radius: 50%; background: #e0e7ff; color: #3730a3; font-size: .75rem; font-weight: 650; }
    .who { display: flex; flex-direction: column; gap: .15rem; min-width: 0; }
    .who strong { font-size: .92rem; }
    .email { color: #6b7280; font-size: .8rem; white-space: nowrap; overflow: hidden; text-overflow: ellipsis; }
    .role { align-self: flex-start; margin-top: .3rem; padding: .05rem .5rem; border-radius: 999px; background: #eff6ff; color: #1d4ed8; font-size: .72rem; font-weight: 500; }
    .role.none { background: #f3f4f6; color: #6b7280; }
  </style>
</head>
<body>
<div class="wrap">
  <header>
    <div class="logo">IT</div>
    <div>
      <h1>Choose a test account <span class="tag">Local only</span></h1>
      <p>Mock company sign-in for local development. Pick who you want to be; their roles decide what you can see and do.</p>
    </div>
  </header>
${sections}
</div>
</body>
</html>
`;

writeFileSync(path.resolve(import.meta.dirname, "..", "mock-oidc", "login.html"), html);
console.log(`mock-oidc/login.html: ${PERSONAS.length} personas`);
